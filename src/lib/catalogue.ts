// Generated by `python -m generator` in korzainc/marketplace.
// `id` is `plugin:path`: names are not unique, a plugin may ship two skills sharing one.
export type SkillEntry = CatalogueEntry & {
  path: string;
  plugin: string;
  origin: string;
  agents: string[];
  sourceRepo: string;
  ref: string;
  pinned: boolean;
  /** One value per skill, from CATEGORIES. The union of the two axes it replaced. */
  category: string;
  /** Decides whether the facets apply. "setup" and "meta" are listed but never faceted. */
  kind: "skill" | "setup" | "meta";
  /** The phrases a user would type. Searched, not rendered. */
  jobs: string[];
  /** "Agent + user", "User only" or "Planned". Derived from two front matter flags. */
  invocation: string;
  /** SPDX id read from the LICENSE file at the pinned ref, with where it was read from. */
  licence: { spdx: string; osiApproved: boolean; source: string };
  /** The Korza team that answers for this skill. Null when nobody here does. */
  ownerTeam: string | null;
  /** Support commitment. Null everywhere: every derivable value restates another field. */
  maturity: string | null;
  /** "Live" for a skill in the catalogue today, "Planned" for one we have committed to. */
  status: string;
};

