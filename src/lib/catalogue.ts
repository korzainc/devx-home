// A state machine, not a number: "N behind" only means anything for an entry pinned to a tag.
export type VersionStatus = {
  state: "behind" | "current" | "unpinned" | "no-releases";
  /** The ref the catalogue pins: a tag, or a branch name when unpinned. */
  pinned: string;
  /** Newest upstream tag, or null when upstream publishes none. */
  latest: string | null;
  /** Tags newer than the pinned one. Null unless state is "behind". */
  behind: number | null;
};

